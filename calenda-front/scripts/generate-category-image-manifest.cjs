const fs = require('node:fs/promises');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const categoriesRoot = path.join(projectRoot, 'src', 'app', 'assets', 'img', 'categorie');
const outputPath = path.join(projectRoot, 'src', 'app', 'core', 'category-image-manifest.ts');
const IMAGE_EXT_RE = /\.(png|jpe?g|webp|avif|gif|svg)$/i;

async function listDirNames(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  return entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name);
}

async function listImageFiles(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile() && IMAGE_EXT_RE.test(entry.name))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
}

function buildTsContent(mapObj) {
  return [
    '// This file is auto-generated by scripts/generate-category-image-manifest.cjs',
    '// Do not edit manually.',
    '',
    'export const CATEGORY_FOLDER_FILES: Record<string, string[]> = ' + JSON.stringify(mapObj, null, 2) + ';',
    '',
  ].join('\n');
}

async function main() {
  const folders = await listDirNames(categoriesRoot);
  const mapping = {};

  for (const folder of folders.sort((a, b) => a.localeCompare(b))) {
    const folderPath = path.join(categoriesRoot, folder);
    mapping[folder] = await listImageFiles(folderPath);
  }

  const content = buildTsContent(mapping);
  await fs.writeFile(outputPath, content, 'utf8');
  console.log(`Generated ${path.relative(projectRoot, outputPath)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
